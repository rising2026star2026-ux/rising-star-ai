export const getApp = (slug) => APPS.find((a) => a.slug === slug);

/** البدائل: المكتوبة، وإلا برامج من نفس القسم */
export function altsFor(app, n = 3) {
  const list = app.alts.map(getApp).filter(Boolean);
  if (list.length >= n) return list.slice(0, n);
  const more = APPS.filter((a) => a.section === app.section && a.slug !== app.slug && !list.includes(a));
  return [...list, ...more].slice(0, n);
}
