// «خيارات الإجابة» (الزرار الأزرق فوق الشات): لمين الإجابة، وإيه الإضافات اللي العميل عايزها.
// نفس الملف بيستخدمه المتصفح (الواجهة) والسيرفر (تعليمات الموديل) عشان القيم تفضل سليمة.

export const LEVELS = [
  ["general", "معلومة عامة"],
  ["student", "طالب"],
  ["researcher", "باحث / أكاديمي"],
  ["expert", "متخصص"],
];

export const EXTRAS = [
  ["deep", "إجابة أعمق ومدققة", "أسباب ونتايج وآراء مختلفة وأرقام وتواريخ دقيقة"],
  ["sources", "مصادر الإجابة", "بحث على النت ورقم المصدر جنب كل معلومة"],
  ["images", "صور توضيحية", "صور من نتايج البحث تحت الرد"],
  ["sites", "مواقع موثوقة للاستزادة", "روابط سريعة لمواقع موثوقة عن الموضوع"],
  ["refs", "كتب ومراجع", "مراجع ومكتبات تقدر تقرا منها أكتر"],
  ["discuss", "أسئلة للنقاش", "أسئلة تكمّل بيها وتفهم أعمق"],
];

export const DEFAULT_OPTS = { level: "general", deep: false, sources: false, images: false, sites: false, refs: false, discuss: false };

export const DISCUSS_HEAD = "أسئلة للنقاش";

export function cleanOpts(raw) {
  if (!raw || typeof raw !== "object") return null;
  const out = { ...DEFAULT_OPTS };
  if (LEVELS.some(([k]) => k === raw.level)) out.level = raw.level;
  for (const [k] of EXTRAS) out[k] = raw[k] === true;
  return out;
}

/** هل الخيارات دي محتاجة بحث على الإنترنت؟ */
export const optsNeedWeb = (o) => !!o && (o.sources || o.images || o.sites || o.refs);

/** عدد الخيارات المفعّلة (للعرض على الزرار) */
export const optsCount = (o) => (o ? (o.level !== "general" ? 1 : 0) + EXTRAS.filter(([k]) => o[k]).length : 0);

const LEVEL_RULE = {
  general: "",
  student: "الإجابة لطالب: اشرح زي مدرّس شاطر. عرّف المصطلحات المهمة، ورتّب المعلومات بعناوين واضحة، وحط التواريخ والأسماء المهمة في نقاط سهلة الحفظ، واختم بقسم «أهم النقط للمذاكرة» في 4-6 نقاط قصيرة.",
  researcher: "الإجابة لباحث أو أكاديمي: اكتب بالعربية الفصحى الأكاديمية الدقيقة. قدّم السياق التاريخي أو العلمي، والأسباب والنتايج، والآراء المختلفة بين المؤرخين أو العلماء لو موجودة، وفرّق بين المؤكد والمختلف عليه، وحدد التواريخ والأرقام بدقة.",
  expert: "الإجابة لمتخصص: ادخل في التفاصيل الفنية والمصطلحات الدقيقة من غير تبسيط زيادة، وركّز على النقط اللي المتخصص محتاجها فعلاً.",
};

/** تعليمات الموديل حسب الخيارات */
export function optsBlock(o, { hasSearch = false } = {}) {
  if (!o) return "";
  const lines = [];
  if (LEVEL_RULE[o.level]) lines.push(LEVEL_RULE[o.level]);
  if (o.deep) lines.push("المستخدم طالب إجابة أعمق ومدققة جداً: غطّي الموضوع من كل جوانبه المهمة (الخلفية، الأسباب، التفاصيل، النتايج، الآراء المختلفة)، بأرقام وتواريخ وأسماء دقيقة، وراجع كل معلومة قبل ما تكتبها، ولو فيه معلومة مش متأكد منها قول كده صراحة.");
  if (o.sources && hasSearch) lines.push("حط رقم المصدر [n] جنب كل معلومة أخدتها من نتايج البحث، واختم بسطر «المصادر:».");
  if (o.sites && hasSearch) lines.push("في آخر الرد قسم بعنوان «### مواقع موثوقة للاستزادة» فيه 3-5 روابط من نتايج البحث بس (اسم الموقع وسطر عن اللي فيه، والرابط زي ما هو). ممنوع تخترع روابط.");
  if (o.refs) lines.push(`في آخر الرد قسم بعنوان «### كتب ومراجع» فيه 3-5 مراجع مشهورة فعلاً عن الموضوع (اسم الكتاب والمؤلف)${hasSearch ? "، والأولوية للمراجع اللي ظهرت في نتايج البحث" : ""}. ممنوع تخترع كتب أو مؤلفين: لو مش متأكد من مرجع ما تكتبهوش، واكتب تحت القسم سطر إن المستخدم يتأكد من توفر المرجع في المكتبات أو على Google Books. ولو مفيد اذكر نوع المكتبة أو الأرشيف اللي يلاقي فيه أكتر (زي دار الكتب أو مكتبة جامعية).`);
  if (o.images && hasSearch) lines.push("الصور التوضيحية من نتايج البحث هتظهر تحت الرد لوحدها، فما تكتبش روابط صور في الرد.");
  if (o.discuss) lines.push(`في آخر سطر من الرد اكتب عنوان «### ${DISCUSS_HEAD}» وتحته 3 أسئلة قصيرة مختلفة تكمّل بيها المستخدم الموضوع وتفهمه أعمق، كل سؤال في سطر لوحده يبدأ بـ «- ». ما تكتبش أي حاجة بعدهم.`);
  return lines.length ? `خيارات الإجابة اللي المستخدم اختارها (التزم بيها):\n- ${lines.join("\n- ")}` : "";
}

/** بيفصل أسئلة النقاش من آخر الرد (للعرض كزراير) */
export function splitDiscuss(text) {
  const t = String(text || "");
  const m = t.match(new RegExp(`\\n#{2,4}\\s*${DISCUSS_HEAD}[^\\n]*\\n([\\s\\S]*)$`));
  if (!m) return { body: t, questions: [] };
  const questions = m[1].split("\n").map((l) => l.replace(/^\s*[-*•\d.)]+\s*/, "").trim()).filter((l) => l.length > 3).slice(0, 4);
  return { body: t.slice(0, m.index).trimEnd(), questions };
}
