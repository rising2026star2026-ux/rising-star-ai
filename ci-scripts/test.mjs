import { chromium } from "playwright";
const BASE = "http://localhost:3000";
const log = (n, ok, i = "") => console.log(ok ? "OK " : "BAD", n, String(i).slice(0, 300));
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 420, height: 900 } });
await p.goto(`${BASE}/chat`);
await p.waitForTimeout(6000);
const m = await p.$eval("textarea", (t) => { const bx = t.parentElement; return { fs: getComputedStyle(t).fontSize, bg: getComputedStyle(bx).backgroundColor, bd: getComputedStyle(bx).borderColor }; });
log("composer", parseFloat(m.fs) < 14, JSON.stringify(m));
await p.fill("textarea", "اكتب هنا نص تجريبي لأرى حجم الخط");
await p.screenshot({ path: "ci/chat-blue.png" });
await b.close();
