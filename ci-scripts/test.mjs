import { chromium } from "playwright";
import fs from "node:fs";
fs.rmSync("ci/res", { recursive: true, force: true });
fs.mkdirSync("ci/res", { recursive: true });
const B = "http://localhost:3000";
const b = await chromium.launch();
const errs = [];
const d = await b.newContext({ viewport: { width: 1280, height: 900 } });
const p = await d.newPage();
p.on("pageerror", (e) => errs.push(e.message));
await p.goto(B + "/resources");
await p.waitForTimeout(3500);
await p.screenshot({ path: "ci/res/desk_closed.jpg", type: "jpeg", quality: 55 });
await p.click(".side-chev");
await p.waitForTimeout(500);
await p.screenshot({ path: "ci/res/desk_open.jpg", type: "jpeg", quality: 55 });
await p.click(".side-sub a >> nth=2");
await p.waitForTimeout(1500);
console.log("url after sub click", p.url());
await p.screenshot({ path: "ci/res/desk_cat.jpg", type: "jpeg", quality: 55 });
const m = await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
const q = await m.newPage();
q.on("pageerror", (e) => errs.push(e.message));
await q.goto(B + "/resources/canva");
await q.waitForTimeout(3500);
await q.screenshot({ path: "ci/res/m_cat.jpg", type: "jpeg", quality: 55, fullPage: true });
await q.click(".menu-btn").catch((e) => console.log("menu", e.message));
await q.waitForTimeout(800);
await q.screenshot({ path: "ci/res/m_drawer.jpg", type: "jpeg", quality: 55 });
for (const u of ["/resources", "/resources/courses", "/resources/nope"]) console.log(u, (await fetch(B + u)).status);
console.log("errs", errs.join(" | "));
await b.close();
