import { chromium } from "playwright";
import fs from "fs";
fs.mkdirSync("ci/pr", { recursive: true });
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 412, height: 900 }, deviceScaleFactor: 2, permissions: ["clipboard-read", "clipboard-write"] });
const p = await ctx.newPage();
const errs = [];
p.on("pageerror", (e) => errs.push(String(e)));
await p.goto("http://localhost:3000/prompts", { waitUntil: "networkidle" });
await p.screenshot({ path: "ci/pr/top.png" });
await p.getByRole("button", { name: "عدّل الأقواس" }).first().click();
await p.locator("input[placeholder='اكتب بدلها...']").first().fill("a young woman");
await p.getByRole("button", { name: "نسخ" }).first().click();
await p.waitForTimeout(300);
const clip = await p.evaluate(() => navigator.clipboard.readText());
const cards = await p.locator("article").count();
await p.locator("article").first().screenshot({ path: "ci/pr/card.png" });
await p.getByPlaceholder("دوّر على برومبت: منتج، لوجو، ريل، كاميرا...").fill("لوجو");
await p.waitForTimeout(200);
const cnt2 = await p.locator("article").count();
await p.goto("http://localhost:3000/", { waitUntil: "networkidle" });
await p.getByRole("button", { name: /القائمة|menu/i }).first().click().catch(() => {});
fs.writeFileSync("ci/pr/info.json", JSON.stringify({ cards, clip, cnt2, errs }, null, 1));
await b.close();
