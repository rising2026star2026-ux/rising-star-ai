import { chromium } from "playwright";
import fs from "fs";
fs.mkdirSync("ci/logo", { recursive: true });
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 412, height: 900 }, deviceScaleFactor: 2 });
await p.goto("http://localhost:3000/library", { waitUntil: "networkidle" });
await p.waitForTimeout(2500);
const info = await p.evaluate(() => [...document.querySelectorAll("img[class*=logo]")].map((i) => ({ src: i.src.split("url=")[1]?.split("&")[0], ok: i.complete && i.naturalWidth > 16, w: i.naturalWidth })));
const letters = await p.evaluate(() => document.querySelectorAll("span[class*=logo]").length);
fs.writeFileSync("ci/logo/info.json", JSON.stringify({ n: info.length, ok: info.filter((x) => x.ok).length, letters, bad: info.filter((x) => !x.ok).map((x) => x.src) }, null, 1));
await p.screenshot({ path: "ci/logo/lib-top.png" });
await p.locator("section").first().screenshot({ path: "ci/logo/sec1.png" });
await p.goto("http://localhost:3000/library/qwen-image", { waitUntil: "networkidle" });
await p.waitForTimeout(2000);
await p.screenshot({ path: "ci/logo/tool.png" });
await b.close();
